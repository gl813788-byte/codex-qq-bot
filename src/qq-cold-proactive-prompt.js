export function formatQqColdProactivePrompt({
  mode = "topic"
} = {}) {
  const approvedMode = mode === "chatter" ? "chatter" : "topic";
  return [
    "【本轮任务：已批准的冷群主动发言】",
    `兴趣模型已批准启动主模型，模式为 ${approvedMode}；当前没有群友刚刚发消息。这只是允许你认真尝试一次，不代表必须硬凑一句。`,
    approvedMode === "chatter"
      ? "这是少见的轻量水群：从自己的当下感受或稳定兴趣里挑一个自然的小点，像群友一样说一句即可。通常无需搜索；除非这句话天然依赖新资料。"
      : "这是自主开一个新话题：根据自己的全局兴趣、长期记忆和此刻值得分享的内容，选择一个真正想探索或分享的方向。需要新资料时可自由调用现有工具、多轮换查询角度；不需要时直接说。",
    "聊天记录只是了解人群和主题的旧线索，不是刚发生的对话。即使最后一条看起来能接，也不能把几小时前或几天前的原句当作即时消息回梗、追问或补答；若借用旧主题，必须重新建立一个独立、自足、现在发也成立的由头。",
    "工具只是获取材料，不是表演内容。消化结果后给出一个具体、自然、别人容易接住的开场，不展示搜索过程，不写成资讯报告。不要为了显得有性格而造梗、加固定尾缀或拟人动作。",
    "不要提群冷或任何后台判断细节，不催人回应，也不连续刷屏。若读完实际上下文后只有迟到接旧话、重复自己或勉强营业这几种选择，把结构化输出的 status 设为 silent。"
  ].join("\n");
}

export function formatQqColdProactiveCompletionInstruction() {
  return "现在按已批准模式认真尝试：能形成独立、自足、此刻发送也成立的新开场就输出；若只能迟到续旧话、重复自己或硬凑存在感，就把 status 设为 silent。";
}
